import 'package:halo_contracts/halo_contracts.dart';
import 'package:test/test.dart';

/// The pipe name is derived independently on both sides of the boundary, so it
/// must agree exactly. This test pins the vectors that the Go helper test
/// asserts, turning a silent "UI cannot find host" failure into a unit failure.
void main() {
  group('pipe name derivation', () {
    test('empty base keeps the historical name', () {
      expect(haloPipeNameFor(null), kPipeName);
      expect(haloPipeNameFor(''), kPipeName);
    });

    test('case and separator differences normalise to one pipe', () {
      expect(haloPipeNameFor(r'D:\project\clash-halo\.tmp\live\data'),
          haloPipeNameFor('d:/project/clash-halo/.tmp/live/data'));
    });

    test('different directories get different pipes', () {
      expect(haloPipeNameFor('a'), isNot(haloPipeNameFor('b')));
      expect(haloPipeNameFor('a'), isNot(kPipeName));
    });

    test('known vectors match the Go implementation', () {
      // Values generated by contract.PipeNameFor in Go; if either side changes
      // its hash, this fails instead of the UI quietly losing its host.
      const vectors = <String, String>{
        // Generated by Go contract.PipeNameFor; verified against FNV-1a of
        // "d:/project/clash-halo" (lower-cased, forward slashes).
        'D:/project/clash-halo': '3f9aa21224b50de8',
        'a': 'af63dc4c8601ec8c',
        // A value whose hex form starts with a zero nibble: PowerShell rendered
        // it as "0a8b…" (17 digits) while Go and Dart emit "a8b…" (16). Both
        // vectors above start with a non-zero nibble, so they cannot tell the
        // two renderings apart — and that difference is exactly what made a
        // PowerShell client look for a pipe the host had never created.
        'D:/project/clash-halo/.tmp/rt/data': 'a8b226546c3c1b3a',
      };
      for (final entry in vectors.entries) {
        expect(haloPipeNameFor(entry.key), '$kPipeName-${entry.value}',
            reason: 'Go/Dart pipe hash diverged for ${entry.key}');
      }
    });

    test('non-ASCII paths hash without throwing', () {
      final name = haloPipeNameFor(r'C:\Users\用户\AppData\Local\clash-halo');
      expect(name, startsWith(kPipeName));
      expect(name.length, greaterThan(kPipeName.length));
    });
  });
}
