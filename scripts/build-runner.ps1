#Requires -Version 7.0
<#
.SYNOPSIS
    Builds the Flutter Windows runner (clash-halo.exe) without CMake.

.DESCRIPTION
    The runner is a small C++ shell: five runner sources, the generated plugin
    registrant, five cpp_client_wrapper sources, one .rc and a manifest. CMake
    builds it in a full `flutter build windows`, but the tool is only needed for
    *this* step — cl/link/rc from the installed Visual Studio do the job.

    Everything is written into a batch file and run through VsDevCmd, because
    the compiler needs the environment that script sets up (INCLUDE/LIB/PATH).
    The source list is derived from the directory plus the wrapper's fixed list,
    so adding a runner .cpp does not require touching this file.

    Requires the Visual Studio "Desktop development with C++" workload. It does
    NOT require the C++ CMake component.
#>
param(
    [string]$OutDir = '',
    [switch]$CheckOnly,
    # Leaves the generated batch file in place for inspection.
    [switch]$KeepBat
)

$ErrorActionPreference = 'Stop'

$root = Split-Path $PSScriptRoot -Parent
$flutterDir = Join-Path $root 'apps\flutter'
$runnerDir = Join-Path $flutterDir 'windows\runner'
$windowsDir = Join-Path $flutterDir 'windows'
$ephemeral = Join-Path $windowsDir 'flutter\ephemeral'
$wrapperDir = Join-Path $ephemeral 'cpp_client_wrapper'
$releaseDir = Join-Path $flutterDir 'build\windows\x64\runner\Release'
$objDir = Join-Path $root 'build\runner-obj'
$exe = Join-Path $releaseDir 'clash-halo.exe'

# The wrapper is generated by `flutter assemble`; without it there is nothing to
# link against and the failure has to point at the missing step, not at cl.exe.
$wrapperSources = @(
    'core_implementations.cc'
    'standard_codec.cc'
    'flutter_engine.cc'
    'flutter_view_controller.cc'
    'plugin_registrar.cc'
) | ForEach-Object { Join-Path $wrapperDir $_ }
foreach ($source in $wrapperSources) {
    if (-not (Test-Path $source)) {
        throw "缺少 $source。先运行 pwsh -File scripts/build-windows.ps1（它会执行 flutter assemble），再重试。"
    }
}
$flutterLib = Join-Path $ephemeral 'flutter_windows.dll.lib'
if (-not (Test-Path $flutterLib)) {
    throw "缺少 $flutterLib。先运行 flutter assemble 生成引擎产物。"
}

# Visual Studio, without the CMake component.
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (-not (Test-Path $vswhere)) { throw '找不到 vswhere.exe：本机没有安装 Visual Studio。' }
$vsPath = & $vswhere -latest -products * `
    -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 `
    -property installationPath 2>$null
if ([string]::IsNullOrWhiteSpace($vsPath)) {
    throw '没有找到带 C++ 工具链的 Visual Studio。安装「使用 C++ 的桌面开发」工作负载后重试。'
}
$vsDevCmd = Join-Path $vsPath 'Common7\Tools\VsDevCmd.bat'
if (-not (Test-Path $vsDevCmd)) { throw "找不到 $vsDevCmd" }

if ($CheckOnly) {
    Write-Output "runner 可以构建：$vsPath"
    return
}

# Version fields embedded in the .rc, taken from pubspec so the file properties
# match what Flutter reports. `0.1.0+1` -> 0,1,0,1.
$versionLine = (Get-Content (Join-Path $flutterDir 'pubspec.yaml') |
    Where-Object { $_ -match '^version:\s*' } | Select-Object -First 1)
$version = ($versionLine -replace '^version:\s*', '').Trim()
if ($version -notmatch '^(\d+)\.(\d+)\.(\d+)(?:\+(\d+))?') {
    throw "pubspec.yaml 里的 version 无法解析：$version"
}
$vMajor, $vMinor, $vPatch = $Matches[1], $Matches[2], $Matches[3]
$vBuild = if ($Matches[4]) { $Matches[4] } else { '0' }

$runnerSources = Get-ChildItem $runnerDir -Filter *.cpp -File | ForEach-Object { $_.FullName }
$registrant = Join-Path $windowsDir 'flutter\generated_plugin_registrant.cc'
if (-not (Test-Path $registrant)) {
    throw "缺少 $registrant：没有插件的项目里它是静态文件，请从版本库恢复。"
}

$quote = { param($s) '"' + $s + '"' }
$sources = @($runnerSources) + $registrant + $wrapperSources | ForEach-Object { & $quote $_ }

$defines = @(
    '/DUNICODE', '/D_UNICODE', '/DNOMINMAX', '/D_HAS_EXCEPTIONS=0', '/DNDEBUG'
    "/DFLUTTER_VERSION=\`"$version\`""
    "/DFLUTTER_VERSION_MAJOR=$vMajor"
    "/DFLUTTER_VERSION_MINOR=$vMinor"
    "/DFLUTTER_VERSION_PATCH=$vPatch"
    "/DFLUTTER_VERSION_BUILD=$vBuild"
)
$includes = @(
    "/I`"$windowsDir`""
    "/I`"$ephemeral`""
    "/I`"$wrapperDir\include`""
)

New-Item -ItemType Directory -Force $objDir, $releaseDir | Out-Null
if (Test-Path $exe) { Remove-Item $exe -Force }

$bat = Join-Path $root 'build\_runner-build.bat'
# /Fo needs a *doubled* trailing backslash: MSVC's command-line parser treats
# the sequence backslash-quote as an escaped quote, so /Fo"...\obj\" swallows
# the closing quote and the following source paths become part of the /Fo value
# (cl then stops with D8003 "no source file name").
$objArg = '/Fo"' + $objDir + '\\"'
$lines = @(
    '@echo off',
    "call `"$vsDevCmd`" -arch=amd64 -host_arch=amd64 -no_logo || exit /b 1",
    "cd /d `"$flutterDir`"",
    # /utf-8: runner sources carry UTF-8 comments without a BOM; MSVC would
    # decode them as the ANSI code page, and C4819 warns about the mangling.
    ('cl /nologo /c /EHsc /std:c++17 /W4 /wd4100 /O2 /MD /utf-8 ' +
        ($defines -join ' ') + ' ' + ($includes -join ' ') +
        " $objArg " + ($sources -join ' ')),
    'if errorlevel 1 exit /b 1',
    ("rc /nologo /I `"$runnerDir`" /fo `"$objDir\runner.res`" `"$runnerDir\Runner.rc`""),
    'if errorlevel 1 exit /b 1',
    ('link /nologo /SUBSYSTEM:WINDOWS /OUT:"' + $exe + '" ' +
        "`"$objDir\*.obj`" `"$objDir\runner.res`" " +
        "`"$flutterLib`" dwmapi.lib user32.lib gdi32.lib advapi32.lib shell32.lib ole32.lib uuid.lib " +
        "/MANIFEST:EMBED /MANIFESTINPUT:`"$runnerDir\runner.exe.manifest`""),
    'if errorlevel 1 exit /b 1',
    'exit /b 0'
)
Set-Content -LiteralPath $bat -Value $lines -Encoding ascii

try {
    & cmd /c "`"$bat`""
    if ($LASTEXITCODE -ne 0) { throw "runner 编译失败（cl/link 退出码 $LASTEXITCODE）" }
} finally {
    if (-not $KeepBat) {
        Remove-Item -LiteralPath $bat -Force -ErrorAction SilentlyContinue
    }
}

if (-not (Test-Path $exe)) { throw "没有生成 $exe" }
$size = (Get-Item $exe).Length
Write-Output "runner: $exe ($size bytes)"

if (-not [string]::IsNullOrEmpty($OutDir)) {
    New-Item -ItemType Directory -Force $OutDir | Out-Null
    Copy-Item $exe (Join-Path $OutDir 'clash-halo.exe') -Force
    Write-Output "runner 已部署到 $OutDir"
}
