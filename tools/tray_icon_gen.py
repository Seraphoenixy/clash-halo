"""Emit tray icons as real .ico bytes, baked into the host binary.

Two things this fixes, both measured:

  * `systray.SetIcon` on Windows wants the bytes of an **.ico**, not a PNG. It
    writes them to a temp file and loads that file with
    `LoadImage(.., IMAGE_ICON, .., LR_LOADFROMFILE)`, which rejects a bare PNG —
    the call fails, logs "Unable to set icon", and the tray keeps the default
    blank icon.
  * The icon should say what the proxy is doing. Clash Verge Rev ships three
    tray icons (common / sysproxy / tun) and swaps them with the state; this
    project does the same, in its own palette.

Sizes mirror Verge's tray files (16/24/32/48/64/256) so Windows can pick the
right one for taskbar scaling instead of rescaling a single bitmap.
"""

from __future__ import annotations

import io
import os

from PIL import Image

HEADER = '''// Code generated by tools/build-icons.py. DO NOT EDIT.

package main

import (
	"clash-halo/native/windows/internal/state"
	"clash-halo/native/windows/internal/tray"
)

// Tray icons, keyed by the proxy state they represent. Each value is the bytes
// of a real .ico file: the tray package writes them to a temp file and loads
// that with LoadImage(IMAGE_ICON, LR_LOADFROMFILE), which does not accept PNG.
var (
	// idle: nothing is proxying.
	trayIconIdle = []byte{
'''

MID = '''	}

	// system proxy or core running: traffic is being proxied.
	trayIconActive = []byte{
'''

TAIL = '''	}

	// TUN mode: a kernel-level tunnel owns the routes.
	trayIconTun = []byte{
'''

FOOTER = '''	}
)

// trayIcon picks the icon for the given runtime state.
//
// The icon answers one question — "is this machine's traffic being proxied?" —
// so only the two states that actually take traffic over recolour it. A running
// core is *not* enough: the core is started by the UI whether or not the user
// ever flipped the system proxy switch, and colouring the tray green for a core
// nobody is routing through claims something the app is not doing.
//
// Order matters: TUN wins over the system proxy because both can be on, and TUN
// is the stronger claim about where traffic goes.
func trayIcon(s state.Snapshot) []byte {
	if s.TunState == state.TunEnabled {
		return trayIconTun
	}
	if s.SystemProxy.Enabled {
		return trayIconActive
	}
	return trayIconIdle
}

// applyTrayIcon pushes the icon matching |s| to the notification area.
//
// The icon is only reloaded when the variant actually changes between
// idle / active / tun: loading an .ico costs a temp file and a LoadImage call,
// and a snapshot stream that fires on every log byte would otherwise do it
// continuously. The tooltip is refreshed alongside it because both answer the
// same question ("is it on, and through what?").
var trayIconApplied string

// The return value says whether the variant changed, so the caller can log the
// transition once instead of on every snapshot (which would bury the log the
// tray itself needs to be diagnosable).
func applyTrayIcon(s state.Snapshot) bool {
	key := trayIconKey(s)
	if key == trayIconApplied {
		tray.SetTooltip(trayTooltip(s))
		return false
	}
	trayIconApplied = key
	tray.SetIconAndTooltip(trayIcon(s), trayTooltip(s))
	return true
}

// trayIconAppliedKey reports which variant is currently in the notification
// area, for the host log. "none" means nothing has been applied yet.
func trayIconAppliedKey() string {
	if trayIconApplied == "" {
		return "none"
	}
	return trayIconApplied
}

// trayIconKey names the variant trayIcon would pick.
func trayIconKey(s state.Snapshot) string {
	switch {
	case s.TunState == state.TunEnabled:
		return "tun"
	case s.SystemProxy.Enabled:
		return "active"
	default:
		return "idle"
	}
}
'''


def go_bytes(data: bytes, indent: str = "\t\t") -> str:
    lines = []
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append(indent + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def ico_bytes(images) -> bytes:
    """Assemble a multi-size .ico with one PNG payload per size."""
    images = sorted(images, key=lambda im: im.width)
    blobs = []
    for im in images:
        buf = io.BytesIO()
        im.save(buf, format="PNG")
        blobs.append(buf.getvalue())

    header = (0, 1, len(images))
    out = bytearray()
    out += header[0].to_bytes(2, "little")
    out += header[1].to_bytes(2, "little")
    out += header[2].to_bytes(2, "little")
    offset = 6 + 16 * len(images)
    directory = bytearray()
    for im, blob in zip(images, blobs):
        w = 0 if im.width >= 256 else im.width
        h = 0 if im.height >= 256 else im.height
        directory += bytes([w, h, 0, 0])
        directory += (1).to_bytes(2, "little")
        directory += (32).to_bytes(2, "little")
        directory += len(blob).to_bytes(4, "little")
        directory += offset.to_bytes(4, "little")
        offset += len(blob)
    return bytes(out + directory + b"".join(blobs))


def build(render_fn, paths, target: str) -> None:
    sizes = (16, 24, 32, 48, 64, 256)
    variants = [
        ("idle", dict(fill=(255, 255, 255, 255), disc=(0x6B, 0x4F, 0xBB, 255))),
        ("active", dict(fill=(255, 255, 255, 255), disc=(0x3E, 0x9A, 0x3E, 255))),
        ("tun", dict(fill=(255, 255, 255, 255), disc=(0x0F, 0x6C, 0xBD, 255))),
    ]

    parts = [HEADER]
    for index, (name, kwargs) in enumerate(variants):
        images = [render_fn(s, paths, **kwargs) for s in sizes]
        parts.append(go_bytes(ico_bytes(images)))
        if index == 0:
            parts.append(MID)
        elif index == 1:
            parts.append(TAIL)

    with open(target, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(parts) + FOOTER)
    print(f"wrote {os.path.basename(target)} (3 variants x {len(sizes)} sizes)")
